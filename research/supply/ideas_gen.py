add("J backlog rule", "L_linear", "backK=6,backAt=0.04,backDown=0.08")
add("J backlog rule", "L_optuna", "curve=1,cDown=0.1422,cLo=0.059627,cSteep=1.0451,cDead=0.0070479,cSpan=0.029905,cPow=0.95849,cCap=0.34285")
add("J backlog rule", "L_urgent24h", "backK=8,backAt=0.02,backDown=0.06,backDueH=24")
# K. combinations aimed at the diagnosis
add("K combo", "due0.18+lateW1", "dueCapPer=0.18,lateW=1")
add("K combo", "due0.11+lateW1", "dueCapPer=0.11,lateW=1")
add("K combo", "short-0.06+lateW1", "shortShift=-0.06,lateW=1")
