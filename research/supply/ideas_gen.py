# B. capacity charge shape (a fixed hour per order weighs on short gigs)
for c, l in ((0.5, 4), (0, 4), (0, 5), (0.5, 5), (2, 3), (0.5, 4.5)): add("B capacity charge", f"capConst{c}_lam{l}", f"capConst={c},capLam={l}")
for l in (3, 3.5, 4.5, 5): add("B capacity charge", f"capLam{l}", f"capLam={l}")
# C. price floor and ceiling
