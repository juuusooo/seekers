for v in (0.80, 0.88, 0.90): add("E booking chance", f"hardChance{v}", f"hardChance={v}")
for v in (0.1, 0.3): add("E booking chance", f"hardPrice{v}", f"hardPrice={v}")
# F. day and town caps
for v in (0.11, 0.13, 0.18): add("F day cap", f"due{v}", f"dueCapPer={v}")
for v in (2, 4): add("F town cap", f"townCap{v}", f"capPerDriver={v}")
for v in (0.15, 0.35): add("F full price", f"fullPrice{v}", f"fullPrice={v}")
# G. lateness charge (P(late) on top of the shipped trees)
for v in (0.5, 1, 1.5, 2): add("G lateness charge", f"lateW{v}", f"lateW={v}")
# H. fees: get gigs booked before the last pickup (20 of 25 late orders had no driver in time)
for v in (0.65, 0.75, 0.8): add("H opening fee", f"openMin{v}", f"openMin={v}")
for v in (1.4, 1.8): add("H opening fee", f"openMax{v}", f"openMax={v}")
for v in (0.15, 0.25, 0.3): add("H raises", f"raiseMax{v}", f"raiseMax={v}")
for v in (1.4, 1.8, 2.0): add("H early ramp", f"rampTop{v}", f"rampTop={v}")
for v in (8, 12, 16): add("H early ramp", f"rampWindow{v}h", f"rampWindowH={v}")
for v in (1.2, 1.5): add("H urgent fees", f"steepOpen{v}", f"steepOpen={v}")
for v in (0.1, 0.25): add("H urgent fees", f"steepStep{v}", f"steepStep={v}")
for v in (3, 6, 8): add("H cost of no driver", f"lateCost{v}", f"lateCost={v}")
for v in (0.6, 1.0): add("H late fee", f"lateFee{v}", f"lateFee={v}")
# I. two-car gigs
for v in (2, 3, 6): add("I pairs", f"pairHold{v}h", f"pairHoldH={v}")
for v in (2.5, 4, 8): add("I pairs", f"pairSlack{v}h", f"pairSlackH={v}")
