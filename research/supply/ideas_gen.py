for v in (1.8, 2.2): add("C price ceiling", f"ceil{v}", f"markupMax={v}")
for v in (0.05, 0.15): add("C least profit", f"minProfit{v}", f"minProfit={v}")
# D. same-day options (9% late, 39% of our orders)
for v in (0.03, 0.06, 0.10, -0.03): add("D same-day price", f"sameDay{v:+}", f"sdShift={v}")
